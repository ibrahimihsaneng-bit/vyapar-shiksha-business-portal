export const rawCareers: any[] = [...baseCareers, ...expandedCareers];

export const allCareers: Career[] = rawCareers.map((c: any) => {
  const normTrack = c.durationTrack.endsWith('s') ? c.durationTrack : (`${c.durationTrack}s` as any);
  const normRemote = c.remoteOpportunities.toLowerCase().includes('high')
    ? 'High'
    : c.remoteOpportunities.toLowerCase().includes('medium')
    ? 'Medium'
    : 'Low';

  return {
    ...c,
    durationTrack: normTrack,
    category: c.categoryName,
    dayInTheLifeDuties: c.dailyResponsibilities,
    toolsRequired: c.requiredSoftware.map((s: any) => s.name),
    salaryRangeInr: {
      entryMin: c.entrySalaryRange.min,
      entryMax: c.entrySalaryRange.max,
    },
    remotePotential: normRemote as 'High' | 'Medium' | 'Low',
    portfolioDeliverables: c.portfolioExpectations,
    hardwareRequirements: c.equipmentRequirements.join(', '),
    ethicalCompliance: {
      status: c.ethicalConsiderations.status,
      notes: c.ethicalConsiderations.details,
    },
  };
});

export const careers = allCareers;

export function getCareerBySlug(slug: string): Career | undefined {
  return allCareers.find((c) => c.slug === slug);
}

